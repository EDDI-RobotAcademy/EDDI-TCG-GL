import * as THREE from "three";

// 카드가 스킬을 쓰러 제자리를 비우고 나갔다 오는 일을, 연출과 화면이 함께 다루기 위한 것.
//
// 연출은 카드가 어디에 서야 하는지 모른다. 화면은 연출이 지금 어느 대목인지 모른다.
// 그래서 필요한 것만 주고받는다.
//
// 창 크기가 바뀌면 두 가지가 함께 달라진다.
//   · 카드의 제자리 — 손패와 필드의 줄이 다시 잡힌다
//   · 스킬 자리 — 화면 가운데 아래, 화면 높이에서 나온다
//
// 앞의 것은 화면이 home 을 고쳐서 알려 준다. 뒤의 것은 화면이 직접 카드를 옮기는데,
// 그러려면 카드가 지금 스킬 자리에 서 있는 중인지 알아야 한다. parked 가 그것을 알린다.
export interface SkillTripHandle {
    // 끝나고 돌아갈 자리. 도는 동안 창 크기가 바뀌면 화면이 이 값을 고친다.
    // 연출은 돌아갈 때 이 값을 다시 읽어야 한다.
    readonly home: THREE.Vector3;

    // 카드가 스킬 자리에 서 있는 동안 true. 서기 시작할 때 알리고, 돌아가기 직전에 끈다.
    parked(parked: boolean): void;
}
