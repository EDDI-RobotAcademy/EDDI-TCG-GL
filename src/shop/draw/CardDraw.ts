import {CardRace} from "../../card/race";

// 카드를 뽑는 일이다.
//
// **실제 서비스에서 무엇이 뽑히는지는 서버가 정한다.** 재화를 깎는 것도, 확률을 굴리는
// 것도, 뽑힌 카드를 보유 목록에 넣는 것도 서버 일이다. 클라이언트가 정하면 아무나 고칠 수
// 있다.
//
// 그래서 여기는 **묻는 창구**다. 지금은 이 안에서 굴리고, 서버가 붙으면 이 안이 바뀐다.
// 부르는 쪽은 안 바뀐다 — 전투의 [적어 둔 것으로 판을 차린다] 와 같은 모양이다 (규칙 25).
export interface CardDraw {
    // 이 종족에서 정해진 장수를 뽑는다. 종족이 null 이면 전 종족에서 뽑는다.
    //
    // 같은 카드가 여러 장 나올 수 있다. 뽑기는 덱에서 빼 오는 것이 아니다.
    draw(race: CardRace | null, count: number): Promise<readonly number[]>;
}

// 한 번에 뽑히는 장수.
export const DRAW_COUNT = 10;

// 한 번 뽑는 데 드는 재화.
//
// **아직 깎지 않는다.** 재화를 든 곳이 없고, 그것을 클라이언트가 들면 아무나 고칠 수 있다.
// 서버가 붙으면 서버가 깎는다. 값만 여기 적어 둔다 — 화면에 얼마인지 보여 줄 일이 있고,
// 그때 두 곳에 적히지 않게.
export const DRAW_COST = 200;
